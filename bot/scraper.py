"""Sarkari Result scraper with a resilient multi-source chain.

Data sources, tried in order until one returns jobs:

1. ``mirror``        - sarkariresult.com.cm, a WordPress mirror that is NOT
                       behind CloudFront and answers cloud-host IPs directly.
2. ``original``      - www.sarkariresult.com direct request (works from
                       residential IPs / local machines).
3. ``original-jina`` - www.sarkariresult.com through the r.jina.ai reader
                       proxy (last resort; error pages are detected and
                       treated as failures instead of empty successes).

All markup-specific selectors live in this single module on purpose: when a
site changes its HTML, only this file and its fixtures need updating.
"""
from __future__ import annotations

import asyncio
import logging
import random
import re
from datetime import datetime, timezone
from urllib.parse import urljoin, urlparse

import httpx
from bs4 import BeautifulSoup

from bot import config
from bot.models import JobDetail, JobSummary

logger = logging.getLogger(__name__)


class ScraperError(RuntimeError):
    """Raised when a page cannot be retrieved through any transport."""


# --------------------------------------------------------------------- regexes
# Original site detail URLs: sarkariresult.com/<section>/<slug>/
ORIGINAL_JOB_RE = re.compile(
    r"^https?://(www\.)?sarkariresult\.com/[a-z0-9\-]+/[a-z0-9\-]+/?$",
    re.IGNORECASE,
)
# Mirror job URLs: sarkariresult.com.cm/<single-slug>/
MIRROR_JOB_RE = re.compile(
    r"^https?://sarkariresult\.com\.cm/[a-z0-9][a-z0-9\-]*/?$", re.IGNORECASE
)
ORIGINAL_BLOCKLIST = {
    "latestjob", "results", "result", "admit-card", "answer-key", "syllabus",
    "admission", "contact", "about", "privacy-policy", "disclaimer", "page",
    "category", "tag", "author", "feed", "app", "tools", "mobile-app",
    "important-links",
}
MIRROR_BLOCKLIST = {
    "latest-jobs", "admit-card", "result", "admission", "syllabus",
    "answer-key", "contact", "privacy-policy", "disclaimer", "about", "home",
    "latest-posts", "wp-content", "wp-json", "feed", "sitemap_index.xml",
    "sitemap.xml", "robots.txt",
}
YEAR_RE = re.compile(r"20\d{2}")
JOB_WORD_RE = re.compile(
    r"online form|recruitment|vacanc|bharti|notification|exam|post|jobs?",
    re.IGNORECASE,
)
LAST_DATE_RE = re.compile(r"last date\s*:?\s*(\d{2}/\d{2}/\d{4})", re.IGNORECASE)
MIRROR_DATE_RE = re.compile(
    r"last date\s*:?\s*(\d{1,2})\s+"
    r"(january|february|march|april|may|june|july|august|september|october|"
    r"november|december)\s+(\d{4})",
    re.IGNORECASE,
)
MD_LINK_RE = re.compile(
    r"\[([^\]]+)\]\((https?://[^)\s]+)(?:\s+\"[^\"]*\")?\)"
)
JINA_ERROR_RE = re.compile(
    r"target url returned error|403 error|generated by cloudfront|"
    r"the request could not be satisfied",
    re.IGNORECASE,
)
SOCIAL_HOSTS = {
    "t.me", "telegram.me", "whatsapp.com", "wa.me", "instagram.com",
    "youtube.com", "youtu.be", "x.com", "twitter.com", "facebook.com",
    "play.google.com", "apps.apple.com", "itunes.apple.com", "flaticon.com",
    "sarkariresultportal.com",
}
MONTHS = {
    m: i for i, m in enumerate(
        ["january", "february", "march", "april", "may", "june", "july",
         "august", "september", "october", "november", "december"], start=1)
}


# --------------------------------------------------------------------- helpers
def _clean(text: str) -> str:
    return " ".join(text.split())


def _unescape_md(text: str) -> str:
    return text.replace("\\|", " ").replace("\\#", "#").replace("\\_", "_").strip()


def _normalize_date(day: str, month_name: str, year: str) -> str | None:
    month = MONTHS.get(month_name.lower())
    if not month:
        return None
    try:
        return datetime(int(year), month, int(day)).strftime("%d/%m/%Y")
    except ValueError:
        return None


def _host(url: str) -> str:
    return (urlparse(url).hostname or "").lower().replace("www.", "")


def _is_external(href: str) -> bool:
    host = _host(href)
    if not host:
        return False
    if host.endswith("sarkariresult.com") or host == "sarkariresult.com.cm":
        return False
    return host not in SOCIAL_HOSTS


def _looks_like_pdf(href: str) -> bool:
    return ".pdf" in urlparse(href).path.lower()


# ============================================================ MIRROR PARSERS
def _mirror_job_from_anchor(anchor, base_url: str) -> JobSummary | None:
    href = urljoin(base_url, anchor.get("href", "").split("#")[0])
    if not MIRROR_JOB_RE.match(href):
        return None
    slug = urlparse(href).path.strip("/")
    if slug in MIRROR_BLOCKLIST:
        return None

    title = _clean(anchor.get_text(" ", strip=True))
    if len(title) < 12 or not (YEAR_RE.search(title) or JOB_WORD_RE.search(title)):
        return None

    # The last date lives in the parent <li> text, after the anchor
    last_date = None
    parent = anchor.find_parent("li")
    container_text = parent.get_text(" ", strip=True) if parent else title
    if match := MIRROR_DATE_RE.search(container_text):
        last_date = _normalize_date(*match.groups())
    elif match := LAST_DATE_RE.search(container_text):
        last_date = match.group(1)

    title = re.split(r"\s*[–-]\s*Last Date", title, flags=re.IGNORECASE)[0]
    return JobSummary(
        job_id="/" + slug,
        title=_clean(title),
        url=href,
        last_date=last_date,
    )


def parse_mirror_listing_html(html: str, base_url: str) -> list[JobSummary]:
    soup = BeautifulSoup(html, "html.parser")
    container = (
        soup.select_one(".entry-content")
        or soup.select_one("main")
        or soup.select_one("article")
        or soup
    )
    jobs: dict[str, JobSummary] = {}
    for anchor in container.select('a[href]'):
        summary = _mirror_job_from_anchor(anchor, base_url)
        if summary and summary.job_id not in jobs:
            jobs[summary.job_id] = summary
    return list(jobs.values())


def _line_after(lines: list[str], index: int) -> str:
    """Value for a 'Label :' line - same line after the colon, else next line."""
    line = lines[index]
    if ":" in line:
        tail = line.split(":", 1)[1].strip()
        if tail:
            return tail
    if index + 1 < len(lines):
        return lines[index + 1].strip()
    return ""


def _find_line(lines: list[str], pattern: str) -> int:
    regex = re.compile(pattern, re.IGNORECASE)
    for i, line in enumerate(lines):
        if regex.search(line):
            return i
    return -1


_QUAL_LINE_RE = re.compile(
    r"bachelor|degree|10th|12th|10\+2|iti|diploma|graduat|intermediate|"
    r"high school|matric|b\.tech|b\.e\b|bba|bca|nursing|viii|8th|"
    r"master'?s?\s+degree|post[\s-]?graduat|\bmba\b|\bmca\b|\bm\.tech\b",
    re.IGNORECASE,
)


def _mirror_apply_and_pdf(soup: BeautifulSoup) -> tuple[str | None, str | None]:
    apply_url: str | None = None
    pdf_url: str | None = None

    # Prefer the anchor right under the "Apply Online Link" heading
    heading = soup.find(
        string=lambda t: t and "apply online link" in t.lower()
    )
    if heading is not None:
        node = heading.parent
        for anchor in node.find_all_next("a", href=True):
            if anchor.find_parent(["h1", "h2", "h3", "h4", "strong"]) is not None \
                    and anchor is not heading.parent:
                break
            href = anchor["href"]
            if _is_external(href):
                if _looks_like_pdf(href):
                    pdf_url = pdf_url or href
                elif apply_url is None:
                    apply_url = href
                    break

    # Generic sweep as a safety net
    external = [
        a["href"] for a in soup.find_all("a", href=True) if _is_external(a["href"])
    ]
    for href in external:
        if _looks_like_pdf(href):
            pdf_url = pdf_url or href
        elif apply_url is None and re.search(r"apply|click here|online", href, re.I):
            apply_url = href
    if apply_url is None:
        apply_url = next((h for h in external if not _looks_like_pdf(h)), None)
    return apply_url, pdf_url


def parse_mirror_detail_html(html: str, url: str) -> JobDetail:
    soup = BeautifulSoup(html, "html.parser")
    for tag in soup(["script", "style", "noscript", "svg"]):
        tag.decompose()
    content = soup.select_one(".entry-content") or soup
    lines = [
        line.strip()
        for line in content.get_text("\n").splitlines()
        if line.strip()
    ]
    text = "\n".join(lines)

    # Organisation from the H1, falling back to the <title>
    organization = None
    if soup.h1 and soup.h1.get_text(strip=True):
        organization = _clean(soup.h1.get_text(" ", strip=True))[:120]
    elif soup.title:
        organization = re.split(r"\s*[|\-–]\s*Sarkari", soup.title.text)[0].strip()[:120]

    # Last application date
    last_date = ""
    idx = _find_line(lines, r"apply online last date|last date (for|of)?\s*:")
    if idx >= 0:
        value = _line_after(lines, idx)
        if match := re.match(
            r"(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})", value
        ):
            last_date = _normalize_date(*match.groups()) or value
        else:
            last_date = value[:40]

    # Age limit (label + value on following line)
    age_bits: list[str] = []
    for label in (r"minimum age", r"maximum age"):
        i = _find_line(lines, label)
        if i >= 0:
            age_bits.append(f"{lines[i].rstrip(': ')} {_line_after(lines, i)}")
    age_limit = " | ".join(_clean(b) for b in age_bits)[:220]

    # Eligibility: first qualification sentence after the "Eligibility Criteria"
    # heading; fall back to any qualification keyword line in the page.
    eligibility = ""
    heading_idx = _find_line(lines, r"eligibility criteria|eligibility")
    if heading_idx >= 0:
        for line in lines[heading_idx + 1: heading_idx + 7]:
            if _QUAL_LINE_RE.search(line):
                eligibility = _clean(line)[:600]
                break
    if not eligibility:
        eligibility = next(
            (_clean(line)[:600] for line in lines if _QUAL_LINE_RE.search(line)),
            "",
        )

    important_dates = ""
    idx = _find_line(lines, r"important dates")
    if idx >= 0:
        important_dates = _clean(" ".join(lines[idx:idx + 8]))[:350]

    apply_url, pdf_url = _mirror_apply_and_pdf(soup)

    return JobDetail(
        eligibility=eligibility,
        age_limit=age_limit,
        important_dates=important_dates,
        organization=organization or None,
        apply_url=apply_url,
        notification_pdf=pdf_url,
        raw_text=text[:4000],
    )


# ========================================================== ORIGINAL PARSERS
def _original_summary(url: str, text: str) -> JobSummary | None:
    text = _clean(_unescape_md(text))
    if not ORIGINAL_JOB_RE.match(url):
        return None
    segments = [s for s in urlparse(url).path.split("/") if s]
    if not segments or segments[0] in ORIGINAL_BLOCKLIST:
        return None
    if len(text) < 12 or not YEAR_RE.search(text):
        return None
    last_date = None
    if match := LAST_DATE_RE.search(text):
        last_date = match.group(1)
    title = re.split(r"\s*[\\|]?\s*Last Date", text, flags=re.IGNORECASE)[0]
    return JobSummary(
        job_id=urlparse(url).path.rstrip("/"),
        title=_clean(title.strip(" |")),
        url=url,
        last_date=last_date,
    )


def parse_listing_html(html: str, base_url: str) -> list[JobSummary]:
    soup = BeautifulSoup(html, "html.parser")
    container = (
        soup.select_one("#content") or soup.select_one("main")
        or soup.select_one("article") or soup.select_one(".entry-content") or soup
    )
    jobs: dict[str, JobSummary] = {}
    for anchor in container.select('a[href]'):
        href = urljoin(base_url, anchor.get("href", "").split("#")[0])
        summary = _original_summary(href, anchor.get_text(" ", strip=True))
        if summary and summary.job_id not in jobs:
            jobs[summary.job_id] = summary
    return list(jobs.values())


def parse_listing_markdown(markdown: str, base_url: str) -> list[JobSummary]:
    if JINA_ERROR_RE.search(markdown):
        raise ScraperError("Reader proxy returned the source site's error page")
    jobs: dict[str, JobSummary] = {}
    for raw_text, raw_url in MD_LINK_RE.findall(markdown):
        href = urljoin(base_url, _unescape_md(raw_url).split("#")[0])
        summary = _original_summary(href, raw_text)
        if summary and summary.job_id not in jobs:
            jobs[summary.job_id] = summary
    return list(jobs.values())


def _markdown_to_text_and_links(markdown: str) -> tuple[str, list[tuple[str, str]]]:
    if JINA_ERROR_RE.search(markdown):
        raise ScraperError("Reader proxy returned the source site's error page")
    links = [
        (_clean(_unescape_md(text)), _unescape_md(url))
        for text, url in MD_LINK_RE.findall(markdown)
    ]
    text = MD_LINK_RE.sub(lambda m: m.group(1), markdown)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = text.replace("**", "").replace("##", "")
    text = re.sub(r"[#`*_>]", "", text)
    text = text.replace("\\|", " ").replace("|", " ")
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return "\n".join(lines), links


def _html_to_text_and_links(html: str) -> tuple[str, list[tuple[str, str]]]:
    soup = BeautifulSoup(html, "html.parser")
    for tag in soup(["script", "style", "noscript", "svg"]):
        tag.decompose()
    lines = [
        line.strip()
        for line in soup.get_text("\n").splitlines()
        if line.strip()
    ]
    links = [
        (a.get_text(" ", strip=True), a["href"])
        for a in soup.find_all("a", href=True)
    ]
    return "\n".join(lines), links


def _extract(text: str, patterns: list[str], limit: int) -> str:
    for pattern in patterns:
        if match := re.search(pattern, text, flags=re.IGNORECASE):
            return _clean(match.group(0))[:limit]
    return ""


def _extract_eligibility(text: str) -> str:
    lines = text.splitlines()
    candidates = [
        line for line in lines
        if re.search(r"eligib|qualification", line, re.IGNORECASE)
        and _QUAL_LINE_RE.search(line)
    ]
    if not candidates:
        candidates = [line for line in lines if _QUAL_LINE_RE.search(line)]
    if candidates:
        return _clean(candidates[0])[:600]
    return _extract(text, [r"eligibility[^\n]{0,500}"], limit=600)


def _extract_age(text: str) -> str:
    lines = text.splitlines()
    min_max = [
        line for line in lines
        if re.search(r"(?:minimum|maximum)\s*age", line, re.IGNORECASE)
    ][:2]
    if min_max:
        return " | ".join(_clean(line) for line in min_max)[:220]
    return _extract(text, [r"age limit[^\n]{0,140}"], limit=220)


def _extract_dates(text: str) -> str:
    lines = text.splitlines()
    for index, line in enumerate(lines):
        if re.search(r"important dates", line, re.IGNORECASE):
            return _clean(" ".join(lines[index:index + 4]))[:350]
    return ""


def _pick_apply_url(links: list[tuple[str, str]]) -> tuple[str | None, str | None]:
    apply_url: str | None = None
    pdf_url: str | None = None
    external: list[tuple[str, str]] = []
    for label, href in links:
        if _looks_like_pdf(href):
            pdf_url = pdf_url or href
        if _is_external(href):
            external.append((label, href))
    for label, href in external:
        if re.search(r"apply|click here|online|register", label, re.IGNORECASE):
            apply_url = href
            break
    if apply_url is None and external:
        apply_url = external[0][1]
    return apply_url, pdf_url


def _build_original_detail(text: str, links: list[tuple[str, str]]) -> JobDetail:
    organization = None
    head = "\n".join(text.splitlines()[:6])
    if match := re.search(
        r"(.+?)\s+(?:online form|recruitment|notification|exam|bharti)\b",
        head, flags=re.IGNORECASE,
    ):
        organization = _clean(match.group(1))[:120] or None
    apply_url, pdf_url = _pick_apply_url(links)
    return JobDetail(
        eligibility=_extract_eligibility(text),
        age_limit=_extract_age(text),
        important_dates=_extract_dates(text),
        organization=organization,
        apply_url=apply_url,
        notification_pdf=pdf_url,
        raw_text=text[:4000],
    )


def parse_detail_html(html: str, url: str) -> JobDetail:
    text, links = _html_to_text_and_links(html)
    return _build_original_detail(text, links)


def parse_detail_markdown(markdown: str, url: str) -> JobDetail:
    text, links = _markdown_to_text_and_links(markdown)
    return _build_original_detail(text, links)


# =================================================================== scraper
class SarkariScraper:
    def __init__(self) -> None:
        self._client = httpx.AsyncClient(
            http2=True,
            follow_redirects=True,
            timeout=config.REQUEST_TIMEOUT,
            trust_env=True,  # honours HTTPS_PROXY if the host needs a proxy
            limits=httpx.Limits(max_connections=10, max_keepalive_connections=5),
            headers={
                "User-Agent": config.USER_AGENT,
                "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
                "Accept-Language": "en-IN,en;q=0.9,hi;q=0.8",
                "Referer": "https://www.sarkariresult.com/",
                "Cache-Control": "no-cache",
                "Pragma": "no-cache",
            },
        )
        # Observability state consumed by the /health endpoint and /sources
        self.status: dict = {
            "last_success_at": None,
            "last_success_source": None,
            "last_error": None,
            "consecutive_failures": 0,
            "last_cycle_jobs": 0,
        }

    async def close(self) -> None:
        await self._client.aclose()

    # ------------------------------------------------------------- transports
    async def _get(self, url: str) -> str:
        last_error: Exception | None = None
        for attempt in range(1, config.MAX_RETRIES + 1):
            try:
                response = await self._client.get(url)
                if response.status_code == 200 and response.text.strip():
                    return response.text
                last_error = ScraperError(f"HTTP {response.status_code} for {url}")
                logger.warning("Attempt %d failed: %s", attempt, last_error)
            except httpx.HTTPError as exc:
                last_error = exc
                logger.warning("Attempt %d error for %s: %s", attempt, url, exc)
            await asyncio.sleep(min(2 ** attempt, 10) + random.uniform(0, 0.8))
        raise ScraperError(f"Could not fetch {url}: {last_error}")

    async def _get_via_jina(self, url: str) -> str:
        if not config.USE_JINA_FALLBACK:
            raise ScraperError("Jina fallback disabled")
        jina_url = "https://r.jina.ai/" + url
        headers = {"X-Return-Format": "markdown"}
        if config.JINA_API_KEY:
            headers["Authorization"] = f"Bearer {config.JINA_API_KEY}"
        logger.warning("Trying reader proxy for %s", url)
        response = await self._client.get(jina_url, headers=headers)
        response.raise_for_status()
        body = response.text
        if not body.strip() or JINA_ERROR_RE.search(body):
            raise ScraperError("Reader proxy could not reach the source (blocked)")
        return body

    # ------------------------------------------------------------- source chain
    async def _fetch_listing_from_source(self, source: str) -> list[JobSummary]:
        if source == "mirror":
            url = config.MIRROR_BASE_URL + config.MIRROR_LISTING_PATH
            html = await self._get(url)
            jobs = parse_mirror_listing_html(html, url)
        elif source == "original":
            url = config.ORIGINAL_BASE_URL + config.ORIGINAL_LISTING_PATH
            html = await self._get(url)
            jobs = parse_listing_html(html, url)
        elif source == "original-jina":
            url = config.ORIGINAL_BASE_URL + config.ORIGINAL_LISTING_PATH
            markdown = await self._get_via_jina(url)
            jobs = parse_listing_markdown(markdown, url)
        else:
            raise ScraperError(f"Unknown source '{source}'")
        if not jobs:
            raise ScraperError(f"Source '{source}' returned zero parseable jobs")
        return jobs

    async def fetch_latest_jobs(self) -> list[JobSummary]:
        errors: list[str] = []
        for source in config.SOURCE_ORDER:
            try:
                jobs = await self._fetch_listing_from_source(source)
            except ScraperError as exc:
                logger.warning("Source %s failed: %s", source, exc)
                errors.append(f"{source}: {exc}")
                continue
            logger.info("Fetched %d jobs via source '%s'", len(jobs), source)
            self.status.update(
                last_success_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
                last_success_source=source,
                last_error=None,
                consecutive_failures=0,
                last_cycle_jobs=len(jobs),
            )
            return jobs

        self.status["consecutive_failures"] += 1
        self.status["last_error"] = " | ".join(errors)
        raise ScraperError("All listing sources failed -> " + " | ".join(errors))

    async def fetch_job_detail(self, url: str) -> JobDetail:
        host = _host(url)
        if host == "sarkariresult.com.cm":
            html = await self._get(url)
            return parse_mirror_detail_html(html, url)

        # Original site: direct first, reader proxy second
        try:
            html = await self._get(url)
            return parse_detail_html(html, url)
        except ScraperError:
            markdown = await self._get_via_jina(url)
            return parse_detail_markdown(markdown, url)

    async def source_healthcheck(self) -> list[dict]:
        """Probe every configured source once - used by the owner /sources cmd."""
        report: list[dict] = []
        for source in config.SOURCE_ORDER:
            entry = {"source": source, "ok": False, "jobs": 0, "error": None}
            try:
                jobs = await self._fetch_listing_from_source(source)
                entry.update(ok=True, jobs=len(jobs))
            except ScraperError as exc:
                entry["error"] = str(exc)[:180]
            report.append(entry)
        return report
