# --------------------------------------------------------------------- helpers
def _clean(text: str) -> str:
    return " ".join(text.split())


def _unescape_md(text: str) -> str:
    return text.replace("\\|", " ").replace("\\#", "#").replace("\\_", "_").strip()


def _normalize_date(day: str, month_name: str, year: str) -> str | None:
    month = MONTHS.get(month_name.lower())
    if not month:
        return None
    try:
        return datetime(int(year), month, int(day)).strftime("%d/%m/%Y")
    except ValueError:
        return None


def _host(url: str) -> str:
    return (urlparse(url).hostname or "").lower().replace("www.", "")


def _is_external(href: str) -> bool:
    host = _host(href)
    if not host:
        return False
    if host.endswith("sarkariresult.com") or host == "sarkariresult.com.cm":
        return False
    return host not in SOCIAL_HOSTS


def _looks_like_pdf(href: str) -> bool:
    return ".pdf" in urlparse(href).path.lower()


# ============================================================ MIRROR PARSERS
def _mirror_job_from_anchor(anchor, base_url: str) -> JobSummary | None:
    href = urljoin(base_url, anchor.get("href", "").split("#")[0])
    if not MIRROR_JOB_RE.match(href):
        return None
    slug = urlparse(href).path.strip("/")
    if slug in MIRROR_BLOCKLIST:
        return None

    title = _clean(anchor.get_text(" ", strip=True))
    if len(title) < 12 or not (YEAR_RE.search(title) or JOB_WORD_RE.search(title)):
        return None

    # The last date lives in the parent <li> text, after the anchor
    last_date = None
    parent = anchor.find_parent("li")
    container_text = parent.get_text(" ", strip=True) if parent else title
    if match := MIRROR_DATE_RE.search(container_text):
        last_date = _normalize_date(*match.groups())
    elif match := LAST_DATE_RE.search(container_text):
        last_date = match.group(1)

    title = re.split(r"\s*[–-]\s*Last Date", title, flags=re.IGNORECASE)[0]
    return JobSummary(
        job_id="/" + slug,
        title=_clean(title),
        url=href,
        last_date=last_date,
    )


def parse_mirror_listing_html(html: str, base_url: str) -> list[JobSummary]:
    soup = BeautifulSoup(html, "html.parser")
    container = (
        soup.select_one(".entry-content")
        or soup.select_one("main")
        or soup.select_one("article")
        or soup
    )
    jobs: dict[str, JobSummary] = {}
    for anchor in container.select('a[href]'):
        summary = _mirror_job_from_anchor(anchor, base_url)
        if summary and summary.job_id not in jobs:
            jobs[summary.job_id] = summary
    return list(jobs.values())


def _line_after(lines: list[str], index: int) -> str:
    """Value for a 'Label :' line - same line after the colon, else next line."""
    line = lines[index]
    if ":" in line:
        tail = line.split(":", 1)[1].strip()
        if tail:
            return tail
    if index + 1 < len(lines):
        return lines[index + 1].strip()
    return ""


def _find_line(lines: list[str], pattern: str) -> int:
    regex = re.compile(pattern, re.IGNORECASE)
    for i, line in enumerate(lines):
        if regex.search(line):
            return i
    return -1


_QUAL_LINE_RE = re.compile(
    r"bachelor|degree|10th|12th|10\+2|iti|diploma|graduat|intermediate|"
    r"high school|matric|b\.tech|b\.e\b|bba|bca|nursing|viii|8th|"
    r"master'?s?\s+degree|post[\s-]?graduat|\bmba\b|\bmca\b|\bm\.tech\b",
    re.IGNORECASE,
)


def _mirror_apply_and_pdf(soup: BeautifulSoup) -> tuple[str | None, str | None]:
    apply_url: str | None = None
    pdf_url: str | None = None

    # Prefer the anchor right under the "Apply Online Link" heading
    heading = soup.find(
        string=lambda t: t and "apply online link" in t.lower()
    )
    if heading is not None:
        node = heading.parent
        for anchor in node.find_all_next("a", href=True):
            if anchor.find_parent(["h1", "h2", "h3", "h4", "strong"]) is not None \
                    and anchor is not heading.parent:
                break
            href = anchor["href"]
            if _is_external(href):
                if _looks_like_pdf(href):
                    pdf_url = pdf_url or href
                elif apply_url is None:
                    apply_url = href
                    break

    # Generic sweep as a safety net
    external = [
        a["href"] for a in soup.find_all("a", href=True) if _is_external(a["href"])
    ]
    for href in external:
        if _looks_like_pdf(href):
            pdf_url = pdf_url or href
        elif apply_url is None and re.search(r"apply|click here|online", href, re.I):
            apply_url = href
    if apply_url is None:
        apply_url = next((h for h in external if not _looks_like_pdf(h)), None)
    return apply_url, pdf_url


_AGE_NUM_RE = re.compile(r"\d+")
_HEADING_RE = re.compile(r"[A-Z][A-Za-z ]{4,}:?\s*$")


def _age_ints(lines: list[str], index: int) -> list[int]:
    """Plausible age numbers (14-70) on a label line and the line after it."""
    window = " ".join(lines[index:index + 2])
    return [int(n) for n in _AGE_NUM_RE.findall(window) if 14 <= int(n) <= 70]


def _extract_age_limits(lines: list[str]) -> tuple[int | None, int | None]:
    min_age = max_age = None
    for i, line in enumerate(lines):
        low = line.lower()
        if min_age is None and "minimum age" in low:
            ages = _age_ints(lines, i)
            if ages:
                min_age = ages[0]
        if max_age is None and "maximum age" in low:
            ages = _age_ints(lines, i)
            if ages:
                max_age = ages[-1]
    # Prose fallback, e.g. "minimum age limit is 18 – 21 years"
    if min_age is None or max_age is None:
        joined = " ".join(lines)
        if match := re.search(
            r"minimum age[^\d]{0,30}(\d{2})\s*[–\-to]+\s*(\d{2})\s*years",
            joined, re.IGNORECASE,
        ):
            min_age = min_age or int(match.group(1))
            max_age = max_age or int(match.group(2))
    return min_age, max_age


def _extract_fee(lines: list[str]) -> str:
    start = _find_line(lines, r"application fee")
    if start < 0:
        return ""
    bits: list[str] = []
    for line in lines[start + 1: start + 12]:
        if re.search(
            r"age limit|total post|vacancy details|important dates|salary|pay scale",
            line, re.I,
        ):
            break
        if re.search(r"₹|rs\.?\s*\d", line, re.I):
            bits.append(_clean(line))
        if len(bits) == 3:
            break
    return " | ".join(bits)[:220]


def _extract_salary(lines: list[str]) -> str:
    pattern = re.compile(
        r"salary|pay (scale|level|matrix|band)|grade pay|in.hand salary", re.I
    )
    for i, line in enumerate(lines):
        if not pattern.search(line):
            continue
        # A heading like "Salary / Pay Scale" carries no value - take next line
        if re.search(r"₹|rs\.?\s*\d|\d{2,}", line):
            return _clean(line)[:220]
        if i + 1 < len(lines):
            return _clean(lines[i + 1])[:220]
    return ""


def _extract_og_image(soup: BeautifulSoup) -> str | None:
    meta = soup.find("meta", attrs={"property": "og:image"})
    content = (meta.get("content") if meta else "") or ""
    return content.replace("http://", "https://") or None


# ------------------------------------------------------------ label -> value
# Notification pages publish their facts as "Label : Value" blocks. We read
# them straight from the DOM (and from the plain-text fallback) so that the
# card can show every important date instead of guessing.
_LABEL_VALUE_SPLIT = re.compile(r"^(?P<label>[^:]{2,60}?)\s*:\s*(?P<value>.*)$")
# A bare heading such as "Total Post" whose value sits in the next block
_BARE_LABEL_RE = re.compile(r"^[A-Z][A-Za-z0-9 &/()\-]{2,60}$")
_FILLER_VALUES = {"for", "to", "and", "or", "of", "the", "-", "–"}


def _norm_label(label: str) -> str:
    return re.sub(r"\s+", " ", label).strip().strip(":").strip().lower()


def _next_block_value(tag) -> str:
    """Value that follows a label block (the next sibling paragraph/cell)."""
    sibling = tag.find_next_sibling()
    for _ in range(3):
        if sibling is None:
            break
        if sibling.name in {"h1", "h2", "h3", "h4", "h5", "h6"}:
            sibling = sibling.find_next_sibling()
            continue
        nxt = _clean(sibling.get_text(" ", strip=True))
        if nxt and nxt.lower() not in _FILLER_VALUES:
            return nxt
        sibling = sibling.find_next_sibling()
    return ""


def _label_value_pairs_from_nodes(root) -> dict[str, str]:
    """Collect 'Label : Value' pairs from list items, paragraphs and cells."""
    pairs: dict[str, str] = {}
    for tag in root.find_all(
        ["li", "p", "td", "h2", "h3", "h4", "h5", "h6", "span"]
    ):
        if tag.name == "span" and tag.find(["li", "p", "td", "span"]):
            continue  # wrapper span - the inner element is more precise
        text = _clean(tag.get_text(" ", strip=True))
        if not text or len(text) > 220:
            continue
        match = _LABEL_VALUE_SPLIT.match(text)
        if match:
            label = _norm_label(match.group("label"))
            value = _clean(match.group("value"))
        elif _BARE_LABEL_RE.match(text):
            # "Total Post" heading -> the value is the block right after it
            label = _norm_label(text)
            value = _next_block_value(tag)
        else:
            continue
        if not label or label in pairs:
            continue
        if not value:
            # "Post Date:" on its own line -> take the next sibling block
            value = _next_block_value(tag)
        if value and len(value) <= 220:
            pairs[label] = value
    return pairs


def _label_value_pairs_from_lines(lines: list[str]) -> dict[str, str]:
    """Same idea for the plain-text/markdown fallback path."""
    pairs: dict[str, str] = {}
    for index, line in enumerate(lines):
        text = _clean(line)
        match = _LABEL_VALUE_SPLIT.match(text)
        if match:
            label = _norm_label(match.group("label"))
            value = _clean(match.group("value"))
        elif _BARE_LABEL_RE.match(text):
            label = _norm_label(text)
            value = ""
        else:
            continue
        if not label or label in pairs:
            continue
        if not value and index + 1 < len(lines):
            candidate = _clean(lines[index + 1])
            if (candidate and candidate.lower() not in _FILLER_VALUES
                    and not _LABEL_VALUE_SPLIT.match(candidate)):
                value = candidate
        if value and len(value) <= 220:
            pairs[label] = value
    return pairs


def _first(pairs: dict[str, str], labels: list[str]) -> str:
    """First non-empty value whose label matches one of ``labels``."""
    for wanted in labels:
        for key, value in pairs.items():
            if key == wanted or key.startswith(wanted):
                if value:
                    return value
    return ""


def _table_by_header(soup: BeautifulSoup, header: str) -> BeautifulSoup | None:
    for table in soup.find_all("table"):
        first_row = table.find("tr")
        if first_row is None:
            continue
        cells = [c.get_text(" ", strip=True) for c in first_row.find_all(["th", "td"])]
        if cells and header.lower() in " ".join(cells).lower():
            return table
    return None


def _vacancy_breakdown(soup: BeautifulSoup) -> dict[str, str]:
    """Category -> number of posts from the 'Category Name | No. Of Posts' table."""
    table = _table_by_header(soup, "No. Of Posts")
    if table is None:
        table = _table_by_header(soup, "Number of Posts")
    if table is None:
        return {}
    breakdown: dict[str, str] = {}
    for index, row in enumerate(table.find_all("tr")):
        cells = row.find_all(["td", "th"])
        if len(cells) < 2:
            continue
        label = _clean(cells[0].get_text(" ", strip=True))
        value = _clean(cells[1].get_text(" ", strip=True))
        if index == 0 and label.lower() in {"category name", "category"}:
            continue
        if not label or not value or len(label) > 40:
            continue
        breakdown[label] = value[:20]
    return breakdown


def detect_states(text: str) -> list[str]:
    """Indian states / union territories mentioned in the notice."""
    low = text.lower()
    found: list[str] = []
    for state in STATES:
        for alias in state["aliases"]:
            if alias in low:
                found.append(state["key"])
                break
    return found


def _eligibility_table(soup: BeautifulSoup) -> BeautifulSoup | None:
    """The post/eligibility table (header may say 'Eligibility' or
    'Education Qualification')."""
    for table in soup.find_all("table"):
        first_row = table.find("tr")
        if first_row is None:
            continue
        cells = [c.get_text(" ", strip=True) for c in first_row.find_all(["th", "td"])]
        joined = " ".join(cells).lower()
        if "post name" in joined and ("eligib" in joined or "qualification" in joined):
            return table
    return None


def _link_table(soup: BeautifulSoup) -> dict[str, str]:
    """Map 'Apply Online Link' / 'Official Website' rows to their URLs."""
    result: dict[str, str] = {}
    for table in soup.find_all("table"):
        for row in table.find_all("tr"):
            cells = row.find_all(["td", "th"])
            if len(cells) < 2:
                continue
            label = _clean(cells[0].get_text(" ", strip=True)).lower()
            anchor = cells[1].find("a", href=True)
            if anchor is None:
                continue
            href = anchor["href"]
            if _is_external(href):
                result[label] = href
    return result


def _eligibility_from_tables(soup: BeautifulSoup) -> str:
    """Full eligibility text from the 'Post Name | Eligibility Criteria' table."""
    table = _eligibility_table(soup)
    if table is None:
        return ""
    chunks: list[str] = []
    rows = table.find_all("tr")
    for index, row in enumerate(rows):
        cells = row.find_all(["td", "th"])
        if not cells:
            continue
        header = _clean(cells[0].get_text(" ", strip=True)).lower()
        if index == 0 and "post name" in header:
            continue
        if len(cells) >= 2:
            post_name = _clean(cells[0].get_text(" ", strip=True))
            criteria = _clean(cells[1].get_text(" ", strip=True))
            if not criteria or "read official notification" in criteria.lower():
                continue
            if criteria.lower() in {"eligibility criteria", "education qualification"}:
                continue
            chunks.append(f"{post_name}: {criteria}" if post_name else criteria)
        elif cells:
            chunks.append(_clean(cells[0].get_text(" ", strip=True)))
    return " ".join(chunks)[:1500]


def _section_after(soup: BeautifulSoup, pattern: str, limit: int = 900) -> str:
    """Text that follows a heading like 'How To Fill ... Online Form'."""
    heading = soup.find(string=lambda t: t and re.search(pattern, t, re.I))
    if heading is None:
        return ""
    node = heading.parent
    parts: list[str] = []
    for sibling in node.find_all_next():
        if sibling is node:
            continue
        if sibling.name in {"h1", "h2", "h3"}:
            break
        text = _clean(sibling.get_text(" ", strip=True))
        if text and text not in parts:
            parts.append(text)
        if sum(len(p) for p in parts) > limit:
            break
    return " ".join(parts)[:limit]


def _mode_of_selection(soup: BeautifulSoup) -> str:
    table = _table_by_header(soup, "Mode Of Selection")
    if table is None:
        table = _table_by_header(soup, "Selection Process")
    if table is None:
        return ""
    rows = table.find_all("tr")
    parts: list[str] = []
    for row in rows[1:]:
        cells = [_clean(c.get_text(" ", strip=True)) for c in row.find_all(["td", "th"])]
        parts.extend(c for c in cells if c)
    if not parts:
        cells = [_clean(c.get_text(" ", strip=True)) for c in rows[0].find_all(["td", "th"])]
        parts = [c for c in cells if c]
    return " → ".join(parts)[:300]


def parse_mirror_detail_html(html: str, url: str) -> JobDetail:
    soup = BeautifulSoup(html, "html.parser")
    # The site menu/nav uses the same "Label: value" shape as the notice and
    # would pollute the extracted facts (Admit Card -> Result, ...).
    for tag in soup(["script", "style", "noscript", "svg", "nav", "header",
                     "footer", "aside"]):
        tag.decompose()
    content = soup.select_one(".entry-content") or soup
    lines = [
        line.strip()
        for line in content.get_text("\n").splitlines()
        if line.strip()
    ]
    text = "\n".join(lines)

    # Organisation from the H1, falling back to the <title>
    organization = None
    exam_name = ""
    if soup.h1 and soup.h1.get_text(strip=True):
        exam_name = _clean(soup.h1.get_text(" ", strip=True))[:150]
        organization = exam_name[:120]
    elif soup.title:
        organization = re.split(r"\s*[|\-–]\s*Sarkari", soup.title.text)[0].strip()[:120]
        exam_name = organization

    pairs = _label_value_pairs_from_nodes(content)
    for key, value in _label_value_pairs_from_lines(lines).items():
        pairs.setdefault(key, value)

    # Last application date (listing level + detail page)
    last_date = ""
    idx = _find_line(lines, r"apply online last date|last date to apply")
    if idx >= 0:
        value = _line_after(lines, idx)
        if match := re.match(r"(\d{1,2})\s+([A-Za-z]+)\s+(\d{4})", value):
            last_date = _normalize_date(*match.groups()) or value
        else:
            last_date = value[:40]
    apply_last_date = _first(pairs, [
        "apply online last date", "online apply last date", "online form last date",
        "last date to apply", "application last date", "closing date",
    ])

    # Age limit (label + value on following line)
    age_bits: list[str] = []
    for label in (r"minimum age", r"maximum age"):
        i = _find_line(lines, label)
        if i >= 0:
            age_bits.append(f"{lines[i].rstrip(': ')} {_line_after(lines, i)}")
    age_limit = " | ".join(_clean(b) for b in age_bits)[:220]
    min_age, max_age = _extract_age_limits(lines)
    min_age = min_age or _age_from_pairs(pairs, "minimum age")
    max_age = max_age or _age_from_pairs(pairs, "maximum age")
    if not age_limit and (min_age or max_age):
        age_limit = f"Minimum Age {min_age or '—'} Years | Maximum Age {max_age or '—'} Years"

    fee = _extract_fee(lines) or _first(pairs, ["application fee", "application fees"])
    salary = _extract_salary(lines) or _first(pairs, [
        "salary", "salary pay scale", "pay scale", "pay level", "grade pay",
    ])

    # Eligibility: the table holds the complete text, the heading the summary
    qualification = _eligibility_from_tables(soup)
    eligibility = ""
    heading_idx = _find_line(lines, r"eligibility criteria|eligibility")
    if heading_idx >= 0:
        for line in lines[heading_idx + 1: heading_idx + 7]:
            if _QUAL_LINE_RE.search(line):
                eligibility = _clean(line)[:600]
                break
    if not eligibility:
        eligibility = next(
            (_clean(line)[:600] for line in lines if _QUAL_LINE_RE.search(line)),
            "",
        )
    if not qualification:
        qualification = eligibility

    important_dates = ""
    idx = _find_line(lines, r"important dates")
    if idx >= 0:
        important_dates = _clean(" ".join(lines[idx:idx + 8]))[:350]

    apply_url, pdf_url = _mirror_apply_and_pdf(soup)
    how_to_apply_text = _section_after(soup, r"how to (fill|apply)")[:900]
    links = _link_table(soup)
    official_site = next(
        (url_ for label, url_ in links.items() if "official website" in label),
        None,
    )
    short_notice = next(
        (url_ for label, url_ in links.items() if "short notice" in label), None
    )
    if official_site is None:
        official_site = next(
            (url_ for label, url_ in links.items() if "official notification" in label),
            None,
        )

